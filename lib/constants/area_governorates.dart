  // بناء قاعدة البيانات مع الاحتفاظ بالأسماء المتكررة
  static void _initialize() {
    if (_areas.isNotEmpty) return;

    for (final entry in _sourceAreas.entries) {
      for (final name in entry.value) {
        final key = normalizeName(name);

        if (key.isEmpty) continue;

        _areas.putIfAbsent(key, () => <String>{});
        _areas[key]!.add(entry.key);
      }
    }
  }

  // توحيد الأسماء العربية
  static String normalizeName(String name) {
    if (name.trim().isEmpty) return '';

    return name
        .trim()
        .replaceAll(
          RegExp(r'[\u064B-\u065F\u0670\u0640]'),
          '',
        )
        .replaceAll('أ', 'ا')
        .replaceAll('إ', 'ا')
        .replaceAll('آ', 'ا')
        .replaceAll('ٱ', 'ا')
        .replaceAll('ى', 'ي')
        .replaceAll('ئ', 'ي')
        .replaceAll('ؤ', 'و')
        .replaceAll('ة', 'ه')
        .replaceAll('ک', 'ك')
        .replaceAll('ی', 'ي')
        .replaceAll(RegExp(r'\s+'), ' ');
  }

  // ترجع المحافظة الأولى المرتبطة بالاسم
  static String? getGovernorate(String areaName) {
    _initialize();

    if (areaName.trim().isEmpty) return null;

    final key = normalizeName(areaName);
    final governorates = _areas[key];

    if (governorates == null || governorates.isEmpty) {
      return null;
    }

    return governorates.first;
  }

  // ترجع كل المحافظات المرتبطة بالاسم
  static List<String> getGovernorates(String areaName) {
    _initialize();

    if (areaName.trim().isEmpty) {
      return [];
    }

    final key = normalizeName(areaName);

    return _areas[key]?.toList() ?? [];
  }

  // التحقق من وجود المنطقة
  static bool containsArea(String areaName) {
    _initialize();

    if (areaName.trim().isEmpty) return false;

    return _areas.containsKey(normalizeName(areaName));
  }

  // جميع أسماء المناطق بدون تكرار
  static List<String> getAllAreas() {
    _initialize();

    final result = _areas.keys.toList();
    result.sort();

    return result;
  }

  // قائمة المناطق كـ getter
  static List<String> get areas => getAllAreas();
}
